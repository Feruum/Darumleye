"""Readable CLI-only progress; never print model requests or document content."""

from collections import Counter
from contextlib import contextmanager
import json
import sys
import threading
import time
from typing import Any, TextIO

import structlog

STAGES = {
    "extraction": "Извлечение требований",
    "individual": "Индивидуальная проверка",
    "set": "Проверка набора требований",
    "acceptance_alignment": "Сверка критериев приёмки",
    "reference": "Проверка по регламентам",
    "multi_pair_1": "Валидатор логики и сценариев",
    "multi_pair_2": "Валидатор полноты и контрактов",
    "multi_pair_3": "Валидатор рисков и норм",
    "multi_finalizer": "Финализация экспертных наблюдений",
    "multi_recheck": "Адресная перепроверка",
}
TASK_RECOVERY_MESSAGES = {
    "spec_task_retry": "повтор задачи после временного сбоя провайдера",
    "spec_task_split": "пакет разделён после ошибки валидации",
}

for role, label in {
    "logic_inspector": "Эксперт бизнес-логики",
    "scenario_builder": "Эксперт сценариев",
    "gap_hunter": "Эксперт полноты",
    "contract_inspector": "Эксперт контрактов",
    "risk_inspector": "Эксперт рисков",
}.items():
    STAGES[f"multi_{role}_individual"] = f"{label} · требования"
    STAGES[f"multi_{role}_set"] = f"{label} · документ"


def elapsed_label(seconds: float) -> str:
    seconds = max(0, int(seconds))
    return f"{seconds // 60:02d}:{seconds % 60:02d}"


class ReviewProgress:
    def __init__(self, *, enabled: bool = True, stream: TextIO | None = None):
        self.enabled = enabled
        self.stream = stream if stream is not None else sys.stderr
        self.started = time.monotonic()
        self.last_update = self.started
        self.phase = "Подготовка"
        self.requests = Counter()
        self.responses = Counter()
        self.active = Counter()
        self.lock = threading.RLock()
        self.stop = threading.Event()
        self.thread: threading.Thread | None = None

    @property
    def elapsed(self) -> float:
        return time.monotonic() - self.started

    def line(self, message: str) -> None:
        if not self.enabled:
            return
        with self.lock:
            self.last_update = time.monotonic()
            print(
                f"[{elapsed_label(self.elapsed)}] {message}",
                file=self.stream,
                flush=True,
            )

    def set_phase(self, message: str) -> None:
        with self.lock:
            self.phase = message
            self.line(message)

    def request_started(self, stage: str) -> int:
        with self.lock:
            self.requests[stage] += 1
            self.active[stage] += 1
            number = self.requests[stage]
            self.line(f"{STAGES.get(stage, 'AI-анализ')} — запрос {number} · отправлен")
            return number

    def request_finished(self, stage: str, number: int, success: bool) -> None:
        with self.lock:
            self.active[stage] -= 1
            if success:
                self.responses[stage] += 1
            outcome = "ответ получен" if success else "запрос не завершён"
            self.line(f"{STAGES.get(stage, 'AI-анализ')} — запрос {number} · {outcome}")

    def _heartbeat(self) -> None:
        while not self.stop.wait(1):
            with self.lock:
                if time.monotonic() - self.last_update < 10:
                    continue
                active = sum(self.active.values())
                replies = sum(self.responses.values())
                detail = (
                    f" · запросов в работе: {active}, ответов получено: {replies}"
                    if self.requests
                    else ""
                )
                self.line(f"Выполняется: {self.phase}{detail}…")

    def __enter__(self):
        if self.enabled:
            self.thread = threading.Thread(target=self._heartbeat, daemon=True)
            self.thread.start()
        return self

    def __exit__(self, *_):
        self.stop.set()
        if self.thread is not None:
            self.thread.join()

    def _log_event(self, _logger, _method, event: dict):
        name = event.get("event")
        stage_key = event.get("stage")
        stage = (
            STAGES.get(stage_key, "AI-анализ")
            if isinstance(stage_key, str)
            else "AI-анализ"
        )
        if name in TASK_RECOVERY_MESSAGES:
            self.line(f"{stage} — {TASK_RECOVERY_MESSAGES[name]}")
        elif name == "spec_stage_correction":
            self.line(f"{stage} — ответ требует исправления; выполняется повтор")
            if isinstance(event.get("reason"), str):
                self.line(f"{stage} — {event['reason']}")
        elif name == "spec_stage_validation_failed":
            self.line(f"{stage} — проверка ответа не пройдена: {event.get('reason', 'некорректный результат')}")
        elif name == "spec_stage_failed":
            # These fields are generated by invoke_stage, not by the model or
            # provider. Never print exception messages or response content.
            error_type = event.get("error_type")
            status = event.get("http_status")
            diagnostic = error_type if isinstance(error_type, str) and error_type.isidentifier() and len(error_type) <= 80 else "Ошибка анализа"
            if isinstance(status, int) and 100 <= status <= 599:
                diagnostic += f" · HTTP {status}"
            codes = event.get("validation_codes") or []
            safe_codes = [code for code in codes if isinstance(code, str) and code.isidentifier() and len(code) < 50]
            if safe_codes:
                diagnostic += " · " + ", ".join(safe_codes[:5])
            self.line(f"{stage} — {diagnostic}")
        elif name == "spec_eval_checkpoint_reused":
            self.line(f"{stage} — загружена сохранённая контрольная точка")
        elif name == "spec_eval_rate_limit_wait":
            seconds = event.get("seconds")
            if isinstance(seconds, (int, float)):
                self.line(f"Лимит запросов AI-провайдера — ожидание {seconds:.0f} с")
        elif name == "spec_review_completed":
            self.set_phase("Анализ завершён, сформирован отчёт")
        elif name == "reference_review_unavailable":
            self.line(
                "Дополнительная проверка регламентов недоступна; основной отчёт будет сохранён"
            )
        elif name in {
            "nace_spec_review_unavailable",
            "nace_reference_review_unavailable",
        }:
            self.line("Оценка Drex недоступна; основной результат сохранён")
        # The CLI prints only its allowlisted messages, never raw provider logs.
        raise structlog.DropEvent

    @contextmanager
    def capture_logs(self):
        previous = structlog.get_config()
        structlog.configure(
            processors=[self._log_event], cache_logger_on_first_use=False
        )
        try:
            yield
        finally:
            structlog.configure(**previous)


class ProgressChat:
    """Observe actual model requests in the CLI, without changing pipeline results."""

    def __init__(self, chat: Any, progress: ReviewProgress):
        self.chat = chat
        self.progress = progress
        self.model_name = chat.model_name
        self.max_retries = getattr(chat, "max_retries", 0)
        self.handles_rate_limits = getattr(chat, "handles_rate_limits", False)

    async def ainvoke(self, messages, *args, **kwargs):
        try:
            candidate = json.loads(messages[-1].content).get("stage")
            stage = (
                candidate
                if isinstance(candidate, str) and candidate in STAGES
                else "unknown"
            )
        except (AttributeError, IndexError, TypeError, ValueError):
            stage = "unknown"
        number = self.progress.request_started(stage)
        try:
            result = await self.chat.ainvoke(messages, *args, **kwargs)
        except BaseException:
            self.progress.request_finished(stage, number, False)
            raise
        self.progress.request_finished(stage, number, True)
        return result
