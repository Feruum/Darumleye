"""Prompt-only, authored GLM output constraints. Runtime validators stay strict."""

import json
import re
from collections.abc import Iterable

from pydantic import BaseModel, ValidationError

CONTRACT_VERSION = "GLM-5.3 authored output contract v1"
MAX_CONTRACT_CHARACTERS = 16_000
_AUTHOR_FIELDS = frozenset({
    "requirements", "id", "source_id", "text", "evidence", "start", "end", "quote",
    "checks", "criterion", "status", "comment", "findings", "kind", "severity", "issue",
    "recommendation", "requirement_ids", "criteria", "clarification_question",
    "summary", "set_checks", "readiness_checklist", "availability", "question",
    "counterexamples", "finding_index", "scenario", "outcomes", "extraction_gaps",
    "merges", "disagreements", "summary_ids", "priority_ids", "question_ids", "attention_roles",
    "assessments", "source_reviews", "applicability", "observations", "specification_evidence",
    "reference_evidence", "replacements", "original", "replacement", "question", "value",
})


def _authored(values: Iterable, allowed: set[str]) -> list[str]:
    return list(dict.fromkeys(value for value in values if isinstance(value, str) and value in allowed))


def _ids(rows, pattern: str) -> list[str]:
    # IDs are generated by the Harness, unlike source IDs and text from a document.
    return list(dict.fromkeys(row["id"] for row in rows
                              if isinstance(row, dict) and isinstance(row.get("id"), str)
                              and re.fullmatch(pattern, row["id"])))


def _count(prop: dict, count: int, *, exact: bool = True) -> None:
    prop["maxItems"] = count
    if exact:
        prop["minItems"] = count


def _enum(prop: dict, values: list[str]) -> None:
    # JSON Schema enums cannot be empty; zero-cardinality arrays handle that case.
    if values:
        prop["enum"] = values


def _enum_array(prop: dict, values: list[str], *, exact: bool = False) -> None:
    existing = prop.get("maxItems")
    _count(prop, len(values) if existing is None else min(existing, len(values)), exact=exact)
    prop["uniqueItems"] = True
    _enum(prop["items"], values)


def _required(schema: dict, name: str) -> None:
    required = schema.setdefault("required", [])
    if name not in required:
        required.append(name)


def _review_schema(schema: dict, stage: str, data: dict, authored_criteria: set[str], authored_readiness: set[str]) -> None:
    props, defs = schema.get("properties", {}), schema.get("$defs", {})
    criteria = _authored(data.get("criteria", ()), authored_criteria)
    requirement_ids = _ids(data.get("requirements", []), r"R-\d{3,6}")
    if "IndividualReview" in defs:
        row = defs["IndividualReview"]["properties"]
        _enum(row["id"],requirement_ids)
        _count(row["checks"],len(criteria))
        _count(props["requirements"],len(requirement_ids))
        _enum(defs["Check"]["properties"]["criterion"],criteria)
    if "SetCheck" in defs:
        _enum(defs["SetCheck"]["properties"]["criterion"],criteria)
        _count(props["set_checks"],len(criteria))
    if "Finding" in defs:
        finding = defs["Finding"]["properties"]
        _enum_array(finding["requirement_ids"],requirement_ids)
        _enum_array(finding["criteria"],_authored(data.get("allowed_finding_criteria",criteria),authored_criteria))
        if "IndividualReview" in defs and requirement_ids:
            finding["requirement_ids"]["minItems"] = 1
    if "ReadinessCheck" in defs and "readiness_checklist" in props:
        readiness_ids = _authored(data.get("readiness_criteria",{}),authored_readiness)
        _enum(defs["ReadinessCheck"]["properties"]["id"],readiness_ids)
        partial = bool(data.get("scope"))
        _count(props["readiness_checklist"],len(readiness_ids),exact=not partial)
        if not partial:
            _required(schema,"readiness_checklist")


def _reducer_schema(schema: dict, stage: str, data: dict) -> None:
    props, defs = schema.get("properties", {}), schema.get("$defs", {})
    if "merges" in props:
        groups = data.get("groups", [])
        visible_ids = _ids(groups,r"O-(?:code-)?\d{1,6}")
        visible = set(visible_ids)
        question_ids = _ids([item for item in groups if isinstance(item,dict) and item.get("question_available") is True],
                            r"O-(?:code-)?\d{1,6}")
        for key in ("summary_ids","priority_ids","question_ids"):
            if key in props:
                _enum_array(props[key],question_ids if key=="question_ids" else visible_ids)
        for key, candidate_key in (("merges","candidate_pairs"),("disagreements","disagreement_candidates")):
            candidates = data.get(candidate_key,[])
            actual_pairs = [pair for pair in candidates if isinstance(pair,(list,tuple)) and len(pair)==2
                            and all(isinstance(item,str) and item in visible for item in pair)]
            candidate_ids = {item for pair in actual_pairs for item in pair}
            prop = props[key]
            _count(prop,min(prop.get("maxItems",len(actual_pairs)),len(actual_pairs)),exact=False)
            inner = prop["items"]
            _enum_array(inner,[id_ for id_ in visible_ids if id_ in candidate_ids])
            if candidate_ids:
                inner["minItems"] = 2
                if key=="disagreements":
                    inner["maxItems"] = 2
        if "attention_roles" in props:
            allowed=set(props["attention_roles"]["items"].get("enum",[]))
            roles = _authored([row.get("role") for row in data.get("coverage_cards",[]) if isinstance(row,dict)],allowed)
            # Replace the wider authored Role enum with the actual displayed roles.
            _enum_array(props["attention_roles"],roles)
    if "assessments" in props and "RecheckAssessment" in defs:
        if "disagreements" in data:
            rows = _ids(data.get("disagreements",[]),r"C-\d{1,6}")
            _enum(defs["RecheckAssessment"]["properties"]["id"],rows)
            _count(props["assessments"],len(rows))
            _required(schema,"assessments")
        else:
            _count(props["assessments"],0,exact=False)
            # A group-level conclusion is scalar; avoid an ambiguous null judgment.
            props["status"]={"type":"string","enum":["agrees","disagrees","uncertain"]}
            props["comment"]={"type":"string","minLength":1,"maxLength":1200}
            _required(schema,"status")
            _required(schema,"comment")


def glm_prompt_contract(
    model: str | None, stage: str, data: dict, output: type[BaseModel], *,
    authored_criteria: set[str], authored_readiness: set[str],
) -> str | None:
    if not model or model.rsplit("/",1)[-1].lower()!="glm-5.3":
        return None
    review = stage in {"individual","set"} or bool(re.fullmatch(r"multi_[a-z_]+_(?:individual|set)",stage))
    reducer = stage.startswith("multi_pair_") or stage in {"multi_finalizer","multi_recheck"}
    if not review and not reducer:
        return None
    # model_json_schema returns a fresh dict; never edit the runtime model or
    # convert immutable criteria tuples into mutable payload values.
    schema = output.model_json_schema()
    if review:
        _review_schema(schema,stage,data,authored_criteria,authored_readiness)
    if reducer:
        _reducer_schema(schema,stage,data)
    encoded = json.dumps(schema,ensure_ascii=False,separators=(",",":"))
    if len(encoded)>MAX_CONTRACT_CHARACTERS:
        # Review bounds (500 requirements, 32 groups, 24 recheck rows) fit
        # this limit. Do not truncate mandatory IDs if invariant is violated.
        raise ValueError("Authored output contract exceeds bounded context")
    return (
        "\nReturn exactly one JSON object matching this authored schema. Copy criterion and ID enum values "
        "literally (no synonym, translation or renaming); include each expected requirement and its owned criterion "
        "rows exactly once. Use uncertain when evidence is insufficient, never omit a mandatory row. "
        "For scoped partial readiness obey the indicated upper bound. Schema is output-only, not source text.\n"
        + CONTRACT_VERSION + ":\n" + encoded
    )


def safe_validation_fields(error: ValidationError) -> list[dict]:
    """Bounded diagnostic paths and codes, never message, input, context or model-authored keys."""
    fields=[]
    for detail in error.errors(include_url=False,include_context=False,include_input=False)[:8]:
        code=detail.get("type","")
        if not isinstance(code,str) or not re.fullmatch(r"[a-z0-9_]{1,64}",code):
            code="validation_error"
        location=list(detail.get("loc",()))[:10]
        path=[]
        for index,part in enumerate(location):
            if isinstance(part,int):
                path.append(part)
            elif code=="extra_forbidden" and index==len(location)-1:
                path.append("<extra>")
            elif isinstance(part,str) and part in _AUTHOR_FIELDS:
                path.append(part)
            else:
                path.append("<extra>")
        fields.append({"path":path,"code":code})
    return fields
